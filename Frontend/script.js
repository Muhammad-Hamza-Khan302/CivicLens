/* =====================================================
   DEMO ISSUE DETECTION
===================================================== */

function detectIssueType(
    description
) {

    const text =
        description.toLowerCase();


    if (
        text.includes("pothole") ||
        text.includes("road") ||
        text.includes("street")
    ) {

        return t(
            "potholeRoadDamage"
        );

    }


    if (
        text.includes("light") ||
        text.includes("lamp")
    ) {

        return t(
            "streetlightIssue"
        );

    }


    if (
        text.includes("drain") ||
        text.includes("flood")
    ) {

        return t(
            "drainageFlooding"
        );

    }


    if (
        text.includes("waste") ||
        text.includes("garbage") ||
        text.includes("trash")
    ) {

        return t(
            "wasteManagement"
        );

    }


    return t(
        "civicIssue"
    );

}


/* =====================================================
   DEMO SEVERITY
===================================================== */

function detectSeverity(
    description
) {

    const text =
        description.toLowerCase();


    if (
        text.includes("danger") ||
        text.includes("accident") ||
        text.includes("flood") ||
        text.includes("blocked") ||
        text.includes("major") ||
        text.includes("large")
    ) {

        return "high";

    }


    if (
        text.includes("broken") ||
        text.includes("damage") ||
        text.includes("bad")
    ) {

        return "medium";

    }


    return "low";

}


/* =====================================================
   PRIORITY
===================================================== */

function detectPriority(
    description
) {

    const severity =
        detectSeverity(
            description
        );


    if (
        severity === "high"
    ) {

        return t(
            "urgentPriority"
        );

    }


    if (
        severity === "medium"
    ) {

        return t(
            "normalPriority"
        );

    }


    return t(
        "lowPriority"
    );

}


