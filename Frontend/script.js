function loadSavedUser() {

    const savedUser =
        localStorage.getItem(
            "civic_user"
        );


    if (!savedUser) {
        return;
    }


    try {

        const user =
            JSON.parse(
                savedUser
            );


        startApplication(
            user
        );

    }

    catch (error) {

        console.error(
            "Saved user error:",
            error
        );


        localStorage.removeItem(
            "civic_user"
        );

    }

}


