startCamera.addEventListener(
    "click",
    async () => {

        try {

            if (
                !navigator.mediaDevices ||
                !navigator.mediaDevices.getUserMedia
            ) {

                showToast(
                    t("cameraUnavailable"),
                    t("cameraUnsupported")
                );

                return;

            }


            cameraStream =
                await navigator
                    .mediaDevices
                    .getUserMedia({

                        video: {

                            facingMode: {
                                ideal: "environment"
                            }

                        },

                        audio: false

                    });


            cameraVideo.srcObject =
                cameraStream;


            cameraVideo.style.display =
                "block";


            cameraPlaceholder.style.display =
                "none";


            capturedImage.style.display =
                "none";


            cameraFrame.style.display =
                "block";


            capturePhoto.disabled =
                false;


            retakePhoto.classList.add(
                "hidden"
            );


            startCamera.innerHTML = `
                <i class="fa-solid fa-camera"></i>
                <span data-i18n="cameraReady">Camera Active</span>
            `;


            /*
                We inserted a translation key
                dynamically, so translate it now.
            */

            applyTranslations();


            showToast(
                t("cameraReadyToast"),
                t("pointCamera")
            );

        }

        catch (error) {

            console.error(
                "Camera error:",
                error
            );


            showToast(
                t("cameraPermissionRequired"),
                t("allowCamera")
            );

        }

    }
);


