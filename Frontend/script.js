/* =====================================================
   UTILITY
===================================================== */

function delay(ms) {

    return new Promise(
        resolve =>
            setTimeout(
                resolve,
                ms
            )
    );

}


function capitalize(text) {

    if (!text) {
        return "";
    }


    return text
        .charAt(0)
        .toUpperCase() +
        text.slice(1);

}


