/* =====================================================
   FORMAT ROLE
===================================================== */

function formatRole(role) {

    if (role === "government") {
        return "Government";
    }


    if (role === "admin") {
        return "Administrator";
    }


    return "Citizen";

}


/* =====================================================
   INITIALS
===================================================== */

function getInitials(name) {

    return name
        .split(" ")
        .map(part => part[0])
        .slice(0, 2)
        .join("")
        .toUpperCase();

}


