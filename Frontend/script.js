/* =====================================================
   TRANSLATION HELPERS
===================================================== */

function t(key) {

    return (
        translations[currentLanguage] &&
        translations[currentLanguage][key]
    ) ||
    translations.en[key] ||
    key;

}


function applyTranslations() {

    /* ---------- TEXT ---------- */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;

            const translated =
                t(key);

            if (translated !== key) {

                element.textContent =
                    translated;

            }

        });


    /* ---------- PLACEHOLDERS ---------- */

    document
        .querySelectorAll("[data-i18n-placeholder]")
        .forEach(element => {

            const key =
                element.dataset.i18nPlaceholder;

            element.placeholder =
                t(key);

        });


    /* ---------- TITLES ---------- */

    document
        .querySelectorAll("[data-i18n-title]")
        .forEach(element => {

            const key =
                element.dataset.i18nTitle;

            element.title =
                t(key);

            element.setAttribute(
                "aria-label",
                t(key)
            );

        });


    /* ---------- ROLE ---------- */

    if (currentUser) {

        userRole.textContent =
            formatRole(
                currentUser.role
            );

    }

}


