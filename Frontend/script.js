function filterReports() {

    const search =
        reportSearch.value
            .toLowerCase()
            .trim();


    const rows =
        document.querySelectorAll(
            ".reports-table .table-row"
        );


    rows.forEach(row => {

        const text =
            row.textContent.toLowerCase();


        const matchesSearch =
            !search ||
            text.includes(search);


        const matchesStatus =
            statusFilter.value === "all" ||
            text.includes(
                statusFilter.value
            );


        row.style.display =
            matchesSearch &&
            matchesStatus
                ? "grid"
                : "none";

    });

}


